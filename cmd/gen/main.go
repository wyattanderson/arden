// Command gen generates LDAP schema and Go models from a versioned YAML file.
package main

import (
	"bytes"
	"errors"
	"flag"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"slices"
	"strings"

	"github.com/wyattanderson/arden/gen"
)

func main() {
	if err := run(os.Args[1:], os.Stderr); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run(args []string, stderr io.Writer) error {
	flags := flag.NewFlagSet("gen", flag.ContinueOnError)
	flags.SetOutput(stderr)
	input := flags.String("config", "", "YAML input file")
	out := flags.String("out", "", "Go output root (files go under <package>/)")
	schema := flags.String("schema", "", "schema LDIF output file")
	check := flags.Bool("check", false, "check outputs for drift without writing")
	if err := flags.Parse(args); err != nil {
		if errors.Is(err, flag.ErrHelp) {
			return nil
		}
		return err
	}
	if flags.NArg() != 0 || *input == "" || (*out == "" && *schema == "") {
		return errors.New("usage: gen -config schema.yaml [-out directory] [-schema schema.ldif] [-check]")
	}
	data, err := os.ReadFile(*input)
	if err != nil {
		return err
	}
	c, err := gen.Parse(data)
	if err != nil {
		return err
	}
	result, err := gen.Generate(c)
	if err != nil {
		return err
	}
	outputs := map[string][]byte{}
	if *schema != "" {
		outputs[filepath.Clean(*schema)] = result.Schema
	}
	if *out != "" {
		for name, content := range result.Models {
			file := filepath.Join(*out, filepath.FromSlash(name))
			if _, exists := outputs[file]; exists {
				return fmt.Errorf("duplicate output %s", file)
			}
			outputs[file] = content
		}
	}
	paths := make([]string, 0, len(outputs))
	for file := range outputs {
		paths = append(paths, file)
	}
	slices.Sort(paths)
	var problems []error
	inputAbs, err := filepath.Abs(*input)
	if err != nil {
		return err
	}
	// Preflight all destinations before writing any of them.
	for _, file := range paths {
		abs, err := filepath.Abs(file)
		if err != nil {
			return err
		}
		if abs == inputAbs {
			return errors.New("refusing to overwrite the YAML input")
		}
		if info, err := os.Lstat(file); err == nil && !info.Mode().IsRegular() {
			return fmt.Errorf("output is not a regular file: %s", file)
		}
		current, err := os.ReadFile(file)
		if err != nil && !errors.Is(err, os.ErrNotExist) {
			return err
		}
		if bytes.Equal(current, outputs[file]) && err == nil {
			continue
		}
		if *check {
			problems = append(problems, fmt.Errorf("generated output missing or stale: %s", file))
			continue
		}
		if err == nil && !bytes.HasPrefix(current, []byte("// Code generated by arden gen. DO NOT EDIT.")) && !bytes.HasPrefix(current, []byte("# Code generated by arden gen. DO NOT EDIT.")) {
			return fmt.Errorf("refusing to overwrite handwritten file %s; move it aside before first generation", file)
		}
	}
	if *check {
		return errors.Join(problems...)
	}
	for _, file := range paths {
		if err := atomicWrite(file, outputs[file]); err != nil {
			return err
		}
	}
	return nil
}

func atomicWrite(file string, data []byte) error {
	if err := os.MkdirAll(filepath.Dir(file), 0755); err != nil {
		return err
	}
	temp, err := os.CreateTemp(filepath.Dir(file), ".arden-gen-*")
	if err != nil {
		return err
	}
	defer os.Remove(temp.Name()) //nolint:errcheck // Cleanup after failed writes or successful rename.
	_, writeErr := temp.Write(data)
	closeErr := temp.Close()
	if err := errors.Join(writeErr, closeErr); err != nil {
		return err
	}
	if err := os.Chmod(temp.Name(), 0644); err != nil {
		return err
	}
	if err := os.Rename(temp.Name(), file); err != nil {
		return fmt.Errorf("write %s: %w", strings.TrimSpace(file), err)
	}
	return nil
}
