package main

import (
	"io"
	"os"
	"path/filepath"
	"testing"

	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"
)

func TestGenerateCheckAndProtectFiles(t *testing.T) {
	dir := t.TempDir()
	config := filepath.Join(dir, "client.yaml")
	data, err := os.ReadFile("../../gen/testdata/client.yaml")
	require.NoError(t, err)
	require.NoError(t, os.WriteFile(config, data, 0600))
	model := filepath.Join(dir, "clientmodel", "client_gen.go")
	schema := filepath.Join(dir, "schema.ldif")
	args := []string{"-config", config, "-out", dir, "-schema", schema}
	require.ErrorContains(t, run(append(args, "-check"), io.Discard), "missing or stale")
	_, err = os.Stat(model)
	require.ErrorIs(t, err, os.ErrNotExist)
	require.NoError(t, run(args, io.Discard))
	require.NoError(t, run(append(args, "-check"), io.Discard))
	require.NoError(t, os.WriteFile(model, []byte("// Code generated by arden gen. DO NOT EDIT.\n// stale\n"), 0600))
	require.ErrorContains(t, run(append(args, "-check"), io.Discard), "stale")
	require.NoError(t, run(args, io.Discard))
	require.NoError(t, os.WriteFile(model, []byte("// handwritten\n"), 0600))
	require.ErrorContains(t, run(args, io.Discard), "handwritten")
	current, err := os.ReadFile(model)
	require.NoError(t, err)
	assert.Equal(t, "// handwritten\n", string(current))
	require.ErrorContains(t, run([]string{"-config", config, "-schema", config}, io.Discard), "YAML input")
	current, err = os.ReadFile(config)
	require.NoError(t, err)
	assert.Equal(t, data, current)
}

func TestInvalidConfigurationWritesNothing(t *testing.T) {
	dir := t.TempDir()
	config := filepath.Join(dir, "invalid.yaml")
	require.NoError(t, os.WriteFile(config, []byte("version: 1\nschema:\n  unknownKey: true\n"), 0600))
	output := filepath.Join(dir, "schema.ldif")
	require.Error(t, run([]string{"-config", config, "-schema", output}, io.Discard))
	_, err := os.Stat(output)
	assert.ErrorIs(t, err, os.ErrNotExist)
}
